//! Журнал входов поверх format::login_log. Фиксирует успешные разблокировки;
//! неудачные попытки не пишутся сюда (без DEK их нечем шифровать) — учёт
//! неудачных попыток/лимит попыток входа принадлежит Фазе 12 (там же
//! автоблокировка), это отдельная задача с другим временем жизни данных.

#[derive(Debug, Clone, PartialEq)]
pub struct LoginLogEntry {
    pub username: String,
    pub timestamp: u64,
    pub success: bool,
}
