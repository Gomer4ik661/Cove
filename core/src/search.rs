//! Поиск по File Table — Фаза 9 (ROADMAP.md).
//!
//! FORMAT.md изначально предполагал отдельный персистентный зашифрованный
//! индекс ("линейный скан неприемлем при 100k+ файлах"). Но с Фазы 2 вся
//! File Table целиком декодируется в память при unlock() и живёт там на
//! протяжении всей сессии — поиск это уже не скан зашифрованных страниц на
//! диске с расшифровкой на каждый запрос, а обычный проход по resident
//! Vec<FileEntry> в памяти, что для реалистичных объёмов (сотни тысяч
//! записей) — миллисекунды, не проблема. Поэтому отдельный персистентный
//! индекс (Superblock уже резервирует под него `search_index_offset/len`)
//! сознательно не строится сейчас — это была бы преждевременная
//! оптимизация без измеренной необходимости. Вернуться к этому имеет смысл
//! в Фазе 15, если/когда профилирование на реальных объёмах покажет, что
//! обхода Vec в памяти недостаточно.

use crate::container::FileId;

#[derive(Debug, Clone, Default)]
pub struct SearchQuery {
    pub name_contains: Option<String>,
    pub extension: Option<String>,
    /// "image" | "video" | "audio" | "document" | "other" — та же
    /// классификация по расширению, что и в остальных местах кода.
    pub category: Option<String>,
    /// Если задано — искать только внутри этой папки и её подпапок
    /// (рекурсивно), а не по всему контейнеру.
    pub folder_id: Option<FileId>,
    pub min_size: Option<u64>,
    pub max_size: Option<u64>,
    pub modified_after: Option<u64>,
    pub modified_before: Option<u64>,
    /// `Some(true)` — только избранное (раздел "Избранное", ROADMAP.md Фаза 10).
    pub favorite: Option<bool>,
}
